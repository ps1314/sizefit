export const MISSING = '⟦missing⟧';

/** Translate `key` into `lang`, filling {placeholders} from `params`. */
export function t(lang, key, params = {}) {
  const s = DICT[lang]?.[key];
  if (s == null) return `${MISSING}${key}`;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

/** zh if any preferred browser language starts with "zh", otherwise en. */
export function detectLang(languages = []) {
  return languages.some(l => /^zh/i.test(l || '')) ? 'zh' : 'en';
}

export function initialLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage blocked: fall back to detection */ }
  const nav = typeof navigator !== 'undefined' ? navigator : {};
  return detectLang(nav.languages?.length ? nav.languages : [nav.language]);
}

export function saveLang(lang) {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
}
